// Contrast requirements: WCAG 2.x AA for normal text (4.5:1) in light and
// dark modes, AAA (7:1) in high-contrast mode.
const (
	minContrast     = 4.5
	minHighContrast = 7.0
)

// textPairs are (foreground, background) token pairs that carry meaning.
var textPairs = [][2]string{
	{"text", "bg"}, {"text", "panel"}, {"text", "rowHover"},
	{"muted", "panel"}, {"muted", "bg"}, {"muted", "rowHover"},
	{"danger", "panel"}, {"danger", "bg"}, {"danger", "rowHover"},
	{"accent", "panel"}, {"accent", "bg"}, {"accent", "rowHover"}, // links, focus rings
	{"accentText", "accent"}, // primary buttons
}

// File is the operator's theme file (NODDANAS_THEME_FILE).
type File struct {
	Name          string                `json:"name"`
	DefaultAccent string                `json:"defaultAccent"`
	Light         Palette               `json:"light"`
	Dark          Palette               `json:"dark"`
	Accents       map[string]AccentFile `json:"accents"`
}

// AccentFile is an operator-defined accent.
type AccentFile struct {
	Label string  `json:"label"`
	Light Palette `json:"light"`
	Dark  Palette `json:"dark"`
}

// Theme is a validated, ready-to-serve theme.
type Theme struct {
	Name          string
	DefaultAccent string
	Accents       []Accent
	Logo          []byte // re-encoded PNG, or nil
	LogoETag      string
	css           []byte
	cssETag       string
}

var (
	hexColor = regexp.MustCompile(`^#(?:[0-9a-fA-F]{3}|[0-9a-fA-F]{6})$`)
	accentID = regexp.MustCompile(`^[a-z][a-z0-9-]{0,23}$`)
)

// Options are the operator's branding inputs, all optional.
type Options struct {
	ThemeJSON []byte // contents of NODDANAS_THEME_FILE
	Name      string // NODDANAS_BRAND_NAME (overrides the file's name)
	Logo      []byte // contents of NODDANAS_BRAND_LOGO_FILE
}

// Default returns the built-in theme.
func Default() *Theme {
	t, err := Load(Options{})
	if err != nil {
		panic(err) // built-ins are tested; this cannot happen
	}
	return t
}

// Load validates operator branding and builds the theme. All problems are
// reported together.
func Load(o Options) (*Theme, error) {
	var f File
	if len(o.ThemeJSON) > 0 {
		if len(o.ThemeJSON) > 64<<10 {
			return nil, errors.New("theme file is larger than 64 KiB")
		}
		dec := json.NewDecoder(bytes.NewReader(o.ThemeJSON))
		dec.DisallowUnknownFields()
		if err := dec.Decode(&f); err != nil {
			return nil, fmt.Errorf("theme file: %w", err)
		}
	}
	var errs []error
	t := &Theme{Name: "NoddaNAS", DefaultAccent: "blue"}

	name := f.Name
	if o.Name != "" {
		name = o.Name
	}
	if name != "" {
		if err := checkName(name); err != nil {
			errs = append(errs, err)
		} else {
			t.Name = name
		}
	}

	light, err := merge(builtinLight, f.Light, "light")
	errs = append(errs, err...)
	dark, err := merge(builtinDark, f.Dark, "dark")
	errs = append(errs, err...)

	t.Accents = append(t.Accents, builtinAccents...)
	ids := make([]string, 0, len(f.Accents))
	for id := range f.Accents {
		ids = append(ids, id)
	}
	sort.Strings(ids)
	for _, id := range ids {
		af := f.Accents[id]
		if !accentID.MatchString(id) {
			errs = append(errs, fmt.Errorf("accent id %q must match [a-z][a-z0-9-]{0,23}", id))
			continue
		}
		if err := checkName(af.Label); err != nil {
			errs = append(errs, fmt.Errorf("accent %q label: %w", id, err))
			continue
		}
		var a Accent
		var e1, e2 []error
		a.ID, a.Label = id, af.Label
		a.Light, e1 = accentPalette(af.Light, id+".light")
		a.Dark, e2 = accentPalette(af.Dark, id+".dark")
		errs = append(append(errs, e1...), e2...)
		replaced := false
		for i := range t.Accents {
			if t.Accents[i].ID == id {
				t.Accents[i], replaced = a, true
			}
		}
		if !replaced {
			t.Accents = append(t.Accents, a)
		}
	}
	if f.DefaultAccent != "" {
		if t.accent(f.DefaultAccent) == nil {
			errs = append(errs, fmt.Errorf("defaultAccent %q is not a defined accent", f.DefaultAccent))
		} else {
			t.DefaultAccent = f.DefaultAccent
		}
	}
	if len(errs) > 0 {
		return nil, errors.Join(errs...)
	}

	// Contrast: every mode with every accent, plus high contrast.
	for _, a := range t.Accents {
		errs = append(errs, checkContrast(withAccent(light, a.Light), "light mode, accent "+a.ID, minContrast)...)
		errs = append(errs, checkContrast(withAccent(dark, a.Dark), "dark mode, accent "+a.ID, minContrast)...)
	}
	errs = append(errs, checkContrast(highContrast, "high-contrast mode", minHighContrast)...)
	if len(errs) > 0 {
		return nil, errors.Join(errs...)
	}

	if len(o.Logo) > 0 {
		logo, err := SanitizeLogo(o.Logo)
		if err != nil {
			return nil, fmt.Errorf("logo: %w", err)
		}
		t.Logo, t.LogoETag = logo, etag(logo)
	}
	t.css = t.render(light, dark)
	t.cssETag = etag(t.css)
	return t, nil
}

func checkName(s string) error {
	if s == "" || !utf8.ValidString(s) || utf8.RuneCountInString(s) > 40 || strings.TrimSpace(s) != s {
		return errors.New("names must be 1-40 characters without leading or trailing spaces")
	}
	for _, r := range s {
		if unicode.IsControl(r) || r >= 0x202a && r <= 0x202e || r >= 0x2066 && r <= 0x2069 {
			return errors.New("names must not contain control or bidirectional characters")
		}
	}
	return nil
}

// normColor validates and normalizes a color to lowercase #rrggbb.
func normColor(v string) (string, bool) {
	if !hexColor.MatchString(v) {
		return "", false
	}
	v = strings.ToLower(v)
	if len(v) == 4 {
		v = "#" + string([]byte{v[1], v[1], v[2], v[2], v[3], v[3]})
	}
	return v, true
}

func merge(base, over Palette, where string) (Palette, []error) {
	out := Palette{}
	for k, v := range base {
		out[k] = v
	}
	var errs []error
	for k, v := range over {
		if _, ok := tokenCSS[k]; !ok || k == "accent" || k == "accentText" {
			errs = append(errs, fmt.Errorf("%s: unknown token %q (allowed: bg, panel, text, muted, line, danger, rowHover; accents go under \"accents\")", where, k))
			continue
		}
		c, ok := normColor(v)
		if !ok {
			errs = append(errs, fmt.Errorf("%s.%s: %q is not a hex color like #1d1d20", where, k, v))
			continue
		}
		out[k] = c
	}
	return out, errs
}

func accentPalette(p Palette, where string) (Palette, []error) {
	out := Palette{}
	var errs []error
	for _, k := range []string{"accent", "accentText"} {
		c, ok := normColor(p[k])
		if !ok {
			errs = append(errs, fmt.Errorf("%s.%s: %q is not a hex color", where, k, p[k]))
			continue
		}
		out[k] = c
	}
	if len(p) != 2 {
		errs = append(errs, fmt.Errorf("%s: an accent defines exactly accent and accentText", where))
	}
	return out, errs
}

func withAccent(base, accent Palette) Palette {
	out := Palette{}
	for k, v := range base {
		out[k] = v
	}
	for k, v := range accent {
		out[k] = v
	}
	return out
}

func (t *Theme) accent(id string) *Accent {
	for i := range t.Accents {
		if t.Accents[i].ID == id {
			return &t.Accents[i]
		}
	}
	return nil
}

func checkContrast(p Palette, where string, min float64) []error {
	var errs []error
	for _, pair := range textPairs {
		r := Contrast(p[pair[0]], p[pair[1]])
		if r < min {
			errs = append(errs, fmt.Errorf("%s: %s on %s has contrast %.2f:1, needs at least %.1f:1", where, pair[0], pair[1], r, min))
		}
	}
	return errs
}

// Contrast returns the WCAG 2.x contrast ratio of two #rrggbb colors.
func Contrast(a, b string) float64 {
	la, lb := luminance(a), luminance(b)
	if la < lb {
		la, lb = lb, la
	}
	return (la + 0.05) / (lb + 0.05)
}

func luminance(c string) float64 {
	raw, err := hex.DecodeString(strings.TrimPrefix(c, "#"))
	if err != nil || len(raw) != 3 {
		return 0
	}
	ch := func(v byte) float64 {
		s := float64(v) / 255
		if s <= 0.03928 {
			return s / 12.92
		}
		return math.Pow((s+0.055)/1.055, 2.4)
	}
	return 0.2126*ch(raw[0]) + 0.7152*ch(raw[1]) + 0.0722*ch(raw[2])
}

// render produces the stylesheet. Selectors and property names are
// constants here; the only variable parts are validated #rrggbb colors and
// validated accent IDs.
func (t *Theme) render(light, dark Palette) []byte {
	var b strings.Builder
	def := t.accent(t.DefaultAccent)
	decl := func(p Palette) string {
		keys := make([]string, 0, len(p))
		for k := range p {
			keys = append(keys, k)
		}
		sort.Strings(keys)
		var s strings.Builder
		for _, k := range keys {
			fmt.Fprintf(&s, "%s:%s;", tokenCSS[k], p[k])
		}
		return s.String()
	}
	// Cascade layers make precedence explicit instead of a specificity
	// contest: a later layer always wins, so high contrast beats any accent,
	// and an accent beats the mode's default accent.
	//
	// Modes: no data-theme attribute = follow the OS (light/dark, and high
	// contrast when the OS asks for more contrast); data-theme="light",
	// "dark" or "contrast" = the user's explicit choice.
	const osDark = `@media (prefers-color-scheme: dark){`
	const notLight = `:not([data-theme="light"])`
	b.WriteString("/* Generated by NoddaNAS from validated theme tokens. */\n")
	b.WriteString("@layer noddanas-mode, noddanas-accent, noddanas-contrast;\n")

	b.WriteString("@layer noddanas-mode{\n")
	fmt.Fprintf(&b, ":root{color-scheme:light;%s}\n", decl(withAccent(light, def.Light)))
	fmt.Fprintf(&b, "%s:root%s{color-scheme:dark;%s}}\n", osDark, notLight, decl(withAccent(dark, def.Dark)))
	fmt.Fprintf(&b, ":root[data-theme=\"dark\"]{color-scheme:dark;%s}\n", decl(withAccent(dark, def.Dark)))
	b.WriteString("}\n")

	b.WriteString("@layer noddanas-accent{\n")
	for _, a := range t.Accents {
		sel := `[data-accent="` + a.ID + `"]` // a.ID matches ^[a-z][a-z0-9-]{0,23}$
		fmt.Fprintf(&b, ":root%s{%s}\n", sel, decl(a.Light))
		fmt.Fprintf(&b, "%s:root%s%s{%s}}\n", osDark, sel, notLight, decl(a.Dark))
		fmt.Fprintf(&b, ":root[data-theme=\"dark\"]%s{%s}\n", sel, decl(a.Dark))
		fmt.Fprintf(&b, ".swatch%s{background:%s;}\n", sel, a.Light["accent"])
		fmt.Fprintf(&b, "%s:root%s .swatch%s{background:%s;}}\n", osDark, notLight, sel, a.Dark["accent"])
		fmt.Fprintf(&b, ":root[data-theme=\"dark\"] .swatch%s{background:%s;}\n", sel, a.Dark["accent"])
	}
	b.WriteString("}\n")

	b.WriteString("@layer noddanas-contrast{\n")
	fmt.Fprintf(&b, ":root[data-theme=\"contrast\"]{color-scheme:dark;%s}\n", decl(highContrast))
	fmt.Fprintf(&b, "@media (prefers-contrast: more){:root:not([data-theme]){color-scheme:dark;%s}}\n", decl(highContrast))
	b.WriteString("}\n")
	return []byte(b.String())
}

// CSS returns the stylesheet and its ETag.
func (t *Theme) CSS() ([]byte, string) { return t.css, t.cssETag }

func etag(b []byte) string {
	s := sha256.Sum256(b)
	return `"` + hex.EncodeToString(s[:12]) + `"`
}
