// Package theme implements NoddaNAS's theming: built-in light, dark and
// high-contrast modes, a palette of accent colors users can choose from, and
// optional operator branding (name, logo, token overrides, extra accents).
//
// Secure-by-design rules:
//
//   - Themes are design tokens, not CSS. Only an allowlisted set of color
//     tokens can be set, and every value must match a strict hex-color
//     grammar. Nothing a theme supplies can carry url(), @import, selectors,
//     or any other CSS syntax, so a theme can neither inject styles nor make
//     the browser fetch anything. The stylesheet is generated by this package
//     from validated values only, and the page's strict CSP is unchanged.
//   - Every mode and accent combination must pass WCAG contrast thresholds.
//     That is accessibility, and also integrity: a theme must not be able to
//     make security-relevant text (warnings, fingerprints, "delete forever")
//     unreadable. An invalid theme fails closed at startup with every
//     problem listed.
//   - High-contrast mode is fixed and cannot be overridden, so an accessible
//     mode always exists.
//   - Logos are raster images only (SVG can carry script) and are decoded and
//     re-encoded here, which strips anything appended or embedded.
package theme

import (
	"bytes"
	"crypto/sha256"
	"encoding/hex"
	"encoding/json"
	"errors"
	"fmt"
	"math"
	"regexp"
	"sort"
	"strings"
	"unicode"
	"unicode/utf8"
)

// Tokens are the themeable colors. The JSON names are the only keys a theme
// file may use; the CSS names are what the stylesheet defines.
var tokenCSS = map[string]string{
	"bg":         "--bg",
	"panel":      "--panel",
	"text":       "--text",
	"muted":      "--muted",
	"line":       "--line",
	"danger":     "--danger",
	"rowHover":   "--row-hover",
	"accent":     "--accent",
	"accentText": "--accent-text",
}

// Palette maps token names to "#rrggbb" colors.
type Palette map[string]string

// Accent is a selectable accent color with light- and dark-mode variants.
type Accent struct {
	ID    string
	Label string
	Light Palette // "accent" and "accentText"
	Dark  Palette
}

